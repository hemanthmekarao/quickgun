export const RESOURCE_MAP: Record<string, ResourceDef> = Object.fromEntries(RESOURCES.map((r) => [r.key, r]));

export function getResource(key: string): ResourceDef {
  const def = RESOURCE_MAP[key];
  if (!def) throw new Error(`Unknown resource: ${key}`);
  return def;
}

/** Prisma delegate name (camelCase model name). */
export function delegateName(model: string): string {
  return model.charAt(0).toLowerCase() + model.slice(1);
}

/** Model + label field for any ref target (generic resource or core model). */
export function refTarget(ref: string): { model: string; titleField: string } {
  const core = CORE_REF_TARGETS[ref];
  if (core) return core;
  const def = getResource(ref);
  return { model: def.model, titleField: def.titleField };
}
