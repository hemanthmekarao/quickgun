function define(def: ResourceDef): ResourceDef {
  const fields = [...def.fields];
  if (!fields.some((x) => x.key === 'status')) {
    fields.push({ key: 'status', label: 'Status', type: 'string', system: true, default: 'ACTIVE' });
  }
  return { ...def, fields };
}

