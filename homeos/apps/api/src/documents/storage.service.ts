import { Injectable, Logger } from '@nestjs/common';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import { decryptBuffer, encryptBuffer } from '../common/crypto';
import { loadConfig } from '../config';

interface Driver {
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  remove(key: string): Promise<void>;
}

class LocalDriver implements Driver {
  private readonly root: string;
  constructor(dir: string) {
    this.root = resolve(dir);
  }
  private path(key: string): string {
    const full = resolve(join(this.root, key));
    // Keys are generated by the server, but never allow one to escape the storage root.
    if (!full.startsWith(this.root + sep)) throw new Error('Invalid storage key');
    return full;
  }
  async put(key: string, data: Buffer): Promise<void> {
    const p = this.path(key);
    await mkdir(dirname(p), { recursive: true });
    await writeFile(p, data, { mode: 0o600 });
  }
  get(key: string): Promise<Buffer> {
    return readFile(this.path(key));
  }
  async remove(key: string): Promise<void> {
    await rm(this.path(key), { force: true });
  }
}

/** S3-compatible object storage (AWS S3, MinIO, Cloudflare R2, …). Loaded only when configured. */
class S3Driver implements Driver {
  private readonly client: any;
  private readonly sdk: any;
  constructor(private readonly bucket: string, region: string | undefined, endpoint: string | undefined, forcePathStyle: boolean) {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    this.sdk = require('@aws-sdk/client-s3');
    this.client = new this.sdk.S3Client({ region: region ?? 'us-east-1', ...(endpoint ? { endpoint } : {}), forcePathStyle });
  }
  async put(key: string, data: Buffer): Promise<void> {
    await this.client.send(
      new this.sdk.PutObjectCommand({ Bucket: this.bucket, Key: key, Body: data, ContentType: 'application/octet-stream', ServerSideEncryption: 'AES256' }),
    );
  }
  async get(key: string): Promise<Buffer> {
    const res = await this.client.send(new this.sdk.GetObjectCommand({ Bucket: this.bucket, Key: key }));
    return Buffer.from(await res.Body.transformToByteArray());
  }
  async remove(key: string): Promise<void> {
    await this.client.send(new this.sdk.DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

/**
 * Document storage. Every object is encrypted with AES-256-GCM using the application data
 * key before it reaches the storage backend, so files are unreadable to anyone with access
 * to the disk or bucket alone. Files are only ever served through the API.
 */
@Injectable()
export class StorageService {
  private readonly logger = new Logger('Storage');
  private driver: Driver | null = null;

  private get impl(): Driver {
    if (!this.driver) {
      const cfg = loadConfig().storage;
      if (cfg.driver === 's3') {
        if (!cfg.s3Bucket) throw new Error('S3_BUCKET must be set when STORAGE_DRIVER=s3');
        this.driver = new S3Driver(cfg.s3Bucket, cfg.s3Region, cfg.s3Endpoint, cfg.s3ForcePathStyle);
        this.logger.log(`Using S3 storage (bucket ${cfg.s3Bucket})`);
      } else {
        this.driver = new LocalDriver(cfg.localDir);
        this.logger.log(`Using local storage at ${resolve(cfg.localDir)}`);
      }
    }
    return this.driver;
  }

  get driverName(): string {
    return loadConfig().storage.driver;
  }

  async put(key: string, data: Buffer): Promise<void> {
    await this.impl.put(key, encryptBuffer(data, loadConfig().dataKey));
  }

  async get(key: string): Promise<Buffer> {
    return decryptBuffer(await this.impl.get(key), loadConfig().dataKey);
  }

  async remove(key: string): Promise<void> {
    await this.impl.remove(key);
  }
}
